#!/usr/bin/env python3
"""Step 9: the same diagram, drawn by Manim and by the component, side by side.

THE QUESTION
------------
Should authored diagrams be rendered by Manim instead of by the in-house
`Schematic` component? The only way to answer it is to draw the same diagram
both ways and look, so this takes a real scene out of run #1 — S 015, THE
JOINT — and reproduces it in Manim from the SAME layer definitions, the same
palette, the same reveal timings.

Same source of truth on both sides, deliberately: a comparison where the Manim
version was redrawn by hand would be a judgement about the drawing, not about
the route.

    python scripts/manim_schematic_probe.py --project <id> --cut c015
"""
from __future__ import annotations

import argparse
import json
import re
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
OUT = ROOT / "remotion-composer" / "out" / "step9"

#: The composition's own canvas, which the SVG paths are written against.
VIEW_W, VIEW_H = 1920.0, 1080.0


def parse_path(d: str) -> list[tuple[float, float]]:
    """The points of an SVG path. These are all M/L/Z polylines."""
    numbers = [float(n) for n in re.findall(r"-?\d+\.?\d*", d)]
    return list(zip(numbers[0::2], numbers[1::2]))


def write_scene(cut: dict, dest: Path) -> Path:
    """A Manim scene file built from the cut's own layers."""
    layers, reveals, labels = cut["layers"], cut.get("reveals", []), cut.get("labels", [])
    reveal_of = {r["layer_id"]: r for r in reveals}

    body = []
    for layer in layers:
        reveal = reveal_of.get(layer["id"], {})
        at = float(reveal.get("at", 0.0))
        duration = float(reveal.get("duration", 0.5))
        effect = reveal.get("effect", "fade")
        stroke = layer.get("stroke", "#EDE6D8")
        fill = layer.get("fill")
        width = float(layer.get("strokeWidth", 2.5))
        if layer["kind"] == "path":
            points = parse_path(layer["d"])
        elif layer["kind"] == "line":
            points = [(layer["x"], layer["y"]), (layer["x2"], layer["y2"])]
        else:
            continue
        body.append(
            f"        shape = polyline({points!r}, {stroke!r}, "
            f"{fill!r}, {width})\n"
            f"        plan.append(({at!r}, {duration!r}, {effect!r}, shape))")

    for label in labels:
        colour = "ACCENT" if label.get("accent") else "INK"
        body.append(
            f"        text = label({label['text']!r}, {label['x']!r}, "
            f"{label['y']!r}, {colour})\n"
            f"        plan.append(({float(label['at'])!r}, 0.35, 'fade', text))")

    source = f'''"""Generated by scripts/manim_schematic_probe.py — do not edit."""
from manim import *

INK = "#EDE6D8"
ACCENT = "#C08A3E"
BG = "#0C0C0E"

VIEW_W, VIEW_H = {VIEW_W}, {VIEW_H}


def to_scene(x, y):
    """SVG pixel space -> Manim units, 16:9 frame of width 14.222."""
    return np.array([(x / VIEW_W - 0.5) * 14.222222,
                     (0.5 - y / VIEW_H) * 8.0, 0.0])


def polyline(points, stroke, fill, width):
    shape = VMobject()
    shape.set_points_as_corners([to_scene(*p) for p in points]
                                + ([to_scene(*points[0])] if fill else []))
    shape.set_stroke(color=stroke, width=width * 0.9)
    shape.set_fill(color=fill, opacity=1.0 if fill else 0.0)
    return shape


def label(message, x, y, colour):
    text = Text(message.upper(), font="Helvetica", weight=MEDIUM,
                font_size=19, color=colour)
    text.move_to(to_scene(x, y), aligned_edge=LEFT)
    return text


class Joint(Scene):
    def construct(self):
        self.camera.background_color = BG
        plan = []
{chr(10).join(body)}

        plan.sort(key=lambda row: row[0])
        clock = 0.0
        for at, duration, effect, mobject in plan:
            if at > clock:
                self.wait(at - clock)
                clock = at
            if effect == "draw":
                self.play(Create(mobject), run_time=duration)
            elif effect == "slide-in":
                mobject.shift(LEFT * 0.6)
                self.play(mobject.animate.shift(RIGHT * 0.6),
                          FadeIn(mobject), run_time=duration)
            else:
                self.play(FadeIn(mobject), run_time=duration)
            clock += duration
        self.wait(max(0.0, {float(cut["out_seconds"]) - float(cut["in_seconds"])} - clock))
'''
    dest.write_text(source)
    return dest


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--project", required=True)
    ap.add_argument("--cut", default="c015")
    args = ap.parse_args()

    props = json.loads(
        (ROOT / "projects" / args.project / "artifacts" / "render_props.json").read_text())
    cut = next(c for c in props["cuts"] if c["id"] == args.cut)
    OUT.mkdir(parents=True, exist_ok=True)

    scene_file = write_scene(cut, OUT / f"{args.cut}_manim.py")
    print(f"scene -> {scene_file.relative_to(ROOT)}")
    subprocess.run(
        [sys.executable, "-m", "manim", "render", "-qh", "--format", "mp4",
         "--fps", "30", "--media_dir", str(OUT / "media"),
         str(scene_file), "Joint"], check=True, cwd=ROOT)

    produced = sorted((OUT / "media").rglob("Joint.mp4"))
    if produced:
        final = OUT / f"{args.cut}_manim.mp4"
        final.write_bytes(produced[-1].read_bytes())
        print(f"manim -> {final.relative_to(ROOT)}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
