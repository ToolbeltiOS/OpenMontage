"""The renderer runs on the dependencies this tree pins, or the run stops.

WHAT IT WAS
-----------
`runner/remotion-composer/node_modules` was a SYMLINK into the dev
checkout:

    runner/remotion-composer/node_modules
      -> OpenMontage/remotion-composer/node_modules   (733 MB)

So every film the runner has ever rendered used whatever happened to be
installed in a different worktree on a different branch, while this tree's
`package-lock.json` described something else. An `npm install` over there, a
branch switch, or deleting that directory to free disk would have changed
the runner's renderer without touching the runner, and the first thing to
notice would have been the plate pass failing four hours into a Friday.

The link is gone and `npm ci` put 348 MB of its own dependencies in the
runner tree, from the tracked lockfile. This keeps it that way: the check
runs at START, before the lock is taken and before any stage, because that
is the difference between losing a minute and losing an evening.

The block is EXECUTED here, not grepped for. A start check nobody has run
is a comment.
"""
from __future__ import annotations

import os
import subprocess
import textwrap
from pathlib import Path

import pytest

ROOT = Path(__file__).resolve().parents[2]
RUNNER = ROOT / "scripts" / "run_weekly.sh"
RUNNER_COMPOSER = Path("/Users/mac/Developer/wak3up-docs/runner/remotion-composer")

START = "# ── the renderer's own dependencies"
END = "# ── one run at a time"


def the_check() -> str:
    text = RUNNER.read_text()
    assert START in text, "the node_modules start check is gone"
    block = text[text.index(START):text.index(END)]
    assert "COMPOSER_MODULES" in block
    return block


def run_check(tmp_path: Path, make) -> subprocess.CompletedProcess:
    """Run the real block against a fake REPO that `make` sets up."""
    composer = tmp_path / "remotion-composer"
    composer.mkdir(parents=True)
    make(composer)
    script = tmp_path / "check.sh"
    script.write_text(textwrap.dedent("""\
        set -uo pipefail
        REPO="$1"
        say()  { echo "SAY: $*"; }
        fail() { echo "FAIL[$1]: $2" >&2; exit 9; }
    """) + the_check())
    return subprocess.run(["bash", str(script), str(tmp_path)],
                          capture_output=True, text=True)


class TestTheCheckRefusesWhatItShould:
    def test_a_symlink_is_refused(self, tmp_path):
        target = tmp_path / "elsewhere"
        (target / ".bin").mkdir(parents=True)
        done = run_check(tmp_path, lambda c: (c / "node_modules").symlink_to(target))
        assert done.returncode == 9, done.stdout
        assert "SYMLINK" in done.stderr
        assert "npm ci" in done.stderr

    def test_a_missing_directory_is_refused(self, tmp_path):
        done = run_check(tmp_path, lambda c: None)
        assert done.returncode == 9, done.stdout
        assert "missing" in done.stderr
        assert "npm ci, not npm install" in done.stderr

    def test_a_partial_install_is_refused(self, tmp_path):
        """node_modules can exist and still render nothing."""
        def make(composer):
            (composer / "node_modules" / ".bin").mkdir(parents=True)
        done = run_check(tmp_path, make)
        assert done.returncode == 9, done.stdout
        assert "no remotion binary" in done.stderr

    def test_a_real_install_passes(self, tmp_path):
        """The control: if nothing passes, the check is just a stop sign."""
        def make(composer):
            binn = composer / "node_modules" / ".bin"
            binn.mkdir(parents=True)
            remotion = binn / "remotion"
            remotion.write_text("#!/bin/sh\necho ok\n")
            remotion.chmod(0o755)
        done = run_check(tmp_path, make)
        assert done.returncode == 0, done.stderr
        assert "real directory" in done.stdout


class TestItRunsEarly:
    def test_it_is_before_the_lock_and_before_every_stage(self):
        text = RUNNER.read_text()
        check_at = text.index(START)
        for later in ("# ── one run at a time",
                      "# ── 1. which film",
                      "pipeline_stage scene_plan",
                      "# ── 5. publish"):
            assert check_at < text.index(later), (
                f"the node_modules check runs after {later!r}")


class TestTheRunnerTreeRightNow:
    """Not a unit test: the state of the machine the films are made on."""

    def test_node_modules_is_not_a_symlink(self):
        path = RUNNER_COMPOSER / "node_modules"
        if not path.exists():
            pytest.skip("the runner worktree is not on this machine")
        assert not path.is_symlink(), (
            f"{path} is a symlink again, to {os.readlink(path)}")

    def test_it_has_its_own_remotion(self):
        binary = RUNNER_COMPOSER / "node_modules" / ".bin" / "remotion"
        if not RUNNER_COMPOSER.exists():
            pytest.skip("the runner worktree is not on this machine")
        assert binary.exists() and os.access(binary, os.X_OK)

    def test_the_lockfile_that_pins_it_is_tracked(self):
        """`npm ci` installs the lockfile. A lockfile outside git pins
        nothing."""
        done = subprocess.run(
            ["git", "ls-files", "--error-unmatch",
             "remotion-composer/package-lock.json"],
            cwd=ROOT, capture_output=True, text=True)
        assert done.returncode == 0, "package-lock.json is not tracked"
